'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const src=fs.readFileSync('voice/pink-voice-catalog.js','utf8');
const store=new Map();
const sandbox={window:{dispatchEvent:()=>{}},localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},CustomEvent:function(){},Object,JSON};
vm.createContext(sandbox);vm.runInContext(src,sandbox);
const cat=sandbox.window.PinkVoiceCatalog;
assert.ok(cat,'voice catalog missing');
assert.equal(cat.voices.length,30,'Gemini voice catalog must contain 30 voices');
assert.equal(new Set(cat.voices.map(v=>v.name)).size,30,'voice names must be unique');
for(const name of ['Aoede','Kore','Puck','Charon','Gacrux','Sulafat','Achernar','Vindemiatrix'])assert.ok(cat.voices.some(v=>v.name===name),name+' missing');
assert.equal(cat.getPreference().voice,'Aoede');
cat.setPreference({voice:'Sulafat',group:'soft'});assert.equal(cat.getPreference().voice,'Sulafat');assert.equal(cat.getPreference().group,'soft');
cat.setPreference({voice:'not-real'});assert.equal(cat.getPreference().voice,'Sulafat','invalid voice must not overwrite selected voice');
const html=fs.readFileSync('index.html','utf8');assert.match(html,/pink-voice-settings\.css/);assert.ok(html.indexOf('pink-voice-catalog.js')<html.indexOf('pink-neural-tts.js'),'catalog must load before neural TTS');
const tts=fs.readFileSync('voice/pink-neural-tts.js','utf8');assert.match(tts,/PinkVoiceCatalog\?\.getPreference/);
console.log('Pink voice library contracts: PASS');